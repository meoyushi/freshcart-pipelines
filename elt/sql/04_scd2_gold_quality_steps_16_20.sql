-- STEP 19: Six reconstructed SQL quality checks; check 6 is negative loyalty points.
CREATE OR REPLACE VIEW GOLD.QUALITY_CHECKS AS
SELECT 'check_1_null_order_id' CHECK_NAME, COUNT_IF(ORDER_ID IS NULL) PROBLEM_COUNT
FROM GOLD.FCT_ORDERS
UNION ALL
SELECT 'check_2_duplicate_order_id',
       (SELECT COUNT(*) FROM (SELECT ORDER_ID FROM GOLD.FCT_ORDERS GROUP BY ORDER_ID HAVING COUNT(*)>1))
UNION ALL
SELECT 'check_3_null_amount_inr_with_amount',
       COUNT_IF(AMOUNT_INR IS NULL AND AMOUNT IS NOT NULL) FROM GOLD.FCT_ORDERS
UNION ALL
SELECT 'check_4_null_loyalty_points', COUNT_IF(LOYALTY_POINTS IS NULL) FROM GOLD.FCT_ORDERS
UNION ALL
SELECT 'check_5_negative_amount_inr', COUNT_IF(AMOUNT_INR<0) FROM GOLD.FCT_ORDERS
UNION ALL
SELECT 'check_6_negative_loyalty_points', COUNT_IF(LOYALTY_POINTS<0) FROM GOLD.FCT_ORDERS;

-- STEP 20: Show all checks passing, deliberately fail check 6, then remove mock row.
