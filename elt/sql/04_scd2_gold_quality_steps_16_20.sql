-- STEP 16: CRM event history and baseline SCD2.
CREATE SCHEMA IF NOT EXISTS DIM;

CREATE TABLE IF NOT EXISTS BRONZE.MOCK_CRM_TIER_EVENTS (
    CUSTOMER_ID VARCHAR(50),
    EMAIL VARCHAR(150),
    TIER VARCHAR(20),
    EFFECTIVE_FROM DATE
);

MERGE INTO BRONZE.MOCK_CRM_TIER_EVENTS t
USING (
    SELECT 'CUST-01' CUSTOMER_ID, 'priya.k@example.com' EMAIL, 'SILVER' TIER, TO_DATE('2026-01-01') EFFECTIVE_FROM
    UNION ALL SELECT 'CUST-01', 'priya.k@example.com', 'GOLD', TO_DATE('2026-08-20')
    UNION ALL SELECT 'CUST-02', 'arjun.k@yahoo.in', 'SILVER', TO_DATE('2026-01-01')
    UNION ALL SELECT 'CUST-03', 'rohan@example.com', 'SILVER', TO_DATE('2026-01-01')
) s
ON t.CUSTOMER_ID=s.CUSTOMER_ID AND t.TIER=s.TIER AND t.EFFECTIVE_FROM=s.EFFECTIVE_FROM
WHEN NOT MATCHED THEN
INSERT (CUSTOMER_ID, EMAIL, TIER, EFFECTIVE_FROM)
VALUES (s.CUSTOMER_ID, s.EMAIL, s.TIER, s.EFFECTIVE_FROM);

CREATE OR REPLACE TABLE DIM.CUSTOMERS_SCD2 AS
SELECT CUSTOMER_ID, EMAIL, TIER, EFFECTIVE_FROM,
       DATEADD(DAY,-1,LEAD(EFFECTIVE_FROM) OVER (PARTITION BY CUSTOMER_ID ORDER BY EFFECTIVE_FROM)) EFFECTIVE_TO,
       LEAD(EFFECTIVE_FROM) OVER (PARTITION BY CUSTOMER_ID ORDER BY EFFECTIVE_FROM) IS NULL IS_CURRENT
FROM BRONZE.MOCK_CRM_TIER_EVENTS;

ALTER TABLE GOLD.FCT_ORDERS ADD COLUMN IF NOT EXISTS TIER VARCHAR(20);

-- STEP 17: First publish baseline Gold before Arjun's change.
MERGE INTO GOLD.FCT_ORDERS t
USING (
    SELECT o.ORDER_ID,o.CUSTOMER_ID,o.CUSTOMER_NAME,o.ORDER_DATE,o.AMOUNT,o.CURRENCY,o.AMOUNT_INR,
           d.TIER,
           o.AMOUNT_INR/100.0 * CASE d.TIER WHEN 'GOLD' THEN 2.0 WHEN 'SILVER' THEN 1.0 ELSE 0.0 END LOYALTY_POINTS,
           SHA2(CONCAT_WS('|',o.ORDER_ID,o.CUSTOMER_ID,o.ORDER_DATE::VARCHAR,o.AMOUNT::VARCHAR,
                o.CURRENCY,o.AMOUNT_INR::VARCHAR,d.TIER,
                (o.AMOUNT_INR/100.0 * CASE d.TIER WHEN 'GOLD' THEN 2.0 WHEN 'SILVER' THEN 1.0 ELSE 0.0 END)::VARCHAR),256) ROW_HASH
    FROM SILVER.ORDERS_DEDUP o
    JOIN DIM.CUSTOMERS_SCD2 d
      ON o.CUSTOMER_ID=d.CUSTOMER_ID
     AND o.ORDER_DATE>=d.EFFECTIVE_FROM
     AND (d.EFFECTIVE_TO IS NULL OR o.ORDER_DATE<=d.EFFECTIVE_TO)
) s
ON t.ORDER_ID=s.ORDER_ID
WHEN MATCHED AND NVL(t.ROW_HASH,'')<>s.ROW_HASH THEN UPDATE SET
    CUSTOMER_ID=s.CUSTOMER_ID,CUSTOMER_NAME=s.CUSTOMER_NAME,ORDER_DATE=s.ORDER_DATE,
    AMOUNT=s.AMOUNT,CURRENCY=s.CURRENCY,AMOUNT_INR=s.AMOUNT_INR,TIER=s.TIER,
    LOYALTY_POINTS=s.LOYALTY_POINTS,ROW_HASH=s.ROW_HASH,PUBLISHED_AT=CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
WHEN NOT MATCHED THEN INSERT
    (ORDER_ID,CUSTOMER_ID,CUSTOMER_NAME,ORDER_DATE,AMOUNT,CURRENCY,AMOUNT_INR,TIER,LOYALTY_POINTS,PUBLISHED_AT,ROW_HASH)
VALUES
    (s.ORDER_ID,s.CUSTOMER_ID,s.CUSTOMER_NAME,s.ORDER_DATE,s.AMOUNT,s.CURRENCY,s.AMOUNT_INR,s.TIER,
     s.LOYALTY_POINTS,CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,s.ROW_HASH);

CREATE OR REPLACE TEMP TABLE GOLD_BEFORE_ARJUN_EVENT AS
