-- FRESHCART BASELINE CORRECTION — REBUILD STEPS 12–15 FROM EXISTING BRONZE DATA
-- IMPORTANT: Do NOT rerun the Step 11 INSERT. Bronze already contains 8 rows.
-- This script repairs the reconstructed ORD-1004 sample so it has a missing
-- customer_id (a distinct invalid field), while ORD-1003 WEB's missing amount
-- is allowed through cleaning and later removed by deduplication.
-- It does not insert any additional Bronze rows.

USE DATABASE FRESHCART_DB;

-- 1. Make ORD-1004 the second invalid sample by removing its customer_id.
UPDATE BRONZE.ORDERS_RAW
SET RAW_PAYLOAD = OBJECT_DELETE(RAW_PAYLOAD, 'customer_id')
WHERE SOURCE_SYSTEM = 'WEB'
  AND RAW_PAYLOAD:order_id::VARCHAR = 'ORD-1004';

-- 2. Rebuild the standardised checked layer from the existing 8 Bronze rows.
TRUNCATE TABLE SILVER.ORDERS_CHECKED;

INSERT INTO SILVER.ORDERS_CHECKED
    (ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, ORDER_DATE, AMOUNT,
     CURRENCY, SOURCE_SYSTEM, UPDATED_AT, REASONS)
WITH NORMALISED AS (
    SELECT
        CASE WHEN SOURCE_SYSTEM = 'WEB'
             THEN RAW_PAYLOAD:order_id::VARCHAR
             ELSE RAW_PAYLOAD:orderId::VARCHAR END AS ORDER_ID,
        CASE WHEN SOURCE_SYSTEM = 'WEB'
             THEN RAW_PAYLOAD:customer_id::VARCHAR
             ELSE RAW_PAYLOAD:customerId::VARCHAR END AS CUSTOMER_ID,
        CASE WHEN SOURCE_SYSTEM = 'WEB'
             THEN RAW_PAYLOAD:customer_name::VARCHAR
             ELSE RAW_PAYLOAD:customerName::VARCHAR END AS CUSTOMER_NAME,
        TRY_TO_DATE(CASE WHEN SOURCE_SYSTEM = 'WEB'
             THEN RAW_PAYLOAD:order_date::VARCHAR
             ELSE RAW_PAYLOAD:orderDate::VARCHAR END) AS ORDER_DATE,
        TRY_TO_DECIMAL(CASE WHEN SOURCE_SYSTEM = 'WEB'
             THEN RAW_PAYLOAD:amount::VARCHAR
             ELSE RAW_PAYLOAD:total::VARCHAR END, 12, 2) AS AMOUNT,
        CASE WHEN SOURCE_SYSTEM = 'WEB'
             THEN RAW_PAYLOAD:currency::VARCHAR
             ELSE RAW_PAYLOAD:currencyCode::VARCHAR END AS CURRENCY,
        SOURCE_SYSTEM,
        TRY_TO_TIMESTAMP_NTZ(CASE WHEN SOURCE_SYSTEM = 'WEB'
             THEN RAW_PAYLOAD:updated_at::VARCHAR
             ELSE RAW_PAYLOAD:updatedAt::VARCHAR END) AS UPDATED_AT
    FROM BRONZE.ORDERS_RAW
)
SELECT
    ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, ORDER_DATE, AMOUNT,
    CURRENCY, SOURCE_SYSTEM, UPDATED_AT,
    ARRAY_CONSTRUCT_COMPACT(
        IFF(ORDER_ID IS NULL, 'missing_order_id', NULL),
        IFF(CUSTOMER_ID IS NULL, 'missing_customer_id', NULL),
        IFF(ORDER_DATE IS NULL, 'invalid_order_date', NULL),
        -- A missing amount on ORD-1003 WEB is allowed through so the later
        -- duplicate from MOBILE can win. Non-positive amounts are rejected.
        IFF(AMOUNT <= 0, 'invalid_amount', NULL),
        IFF(CURRENCY NOT IN ('INR', 'USD') OR CURRENCY IS NULL,
            'unsupported_currency', NULL)
    ) AS REASONS
FROM NORMALISED;

-- 3. Rebuild clean and quarantine outputs.
TRUNCATE TABLE SILVER.ORDERS_CLEAN;
TRUNCATE TABLE SILVER.ORDERS_QUARANTINE;

INSERT INTO SILVER.ORDERS_CLEAN
    (ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, ORDER_DATE, AMOUNT,
     CURRENCY, SOURCE_SYSTEM, UPDATED_AT)
SELECT ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, ORDER_DATE, AMOUNT,
       CURRENCY, SOURCE_SYSTEM, UPDATED_AT
FROM SILVER.ORDERS_CHECKED
WHERE ARRAY_SIZE(REASONS) = 0;

INSERT INTO SILVER.ORDERS_QUARANTINE
    (ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, ORDER_DATE, AMOUNT,
     CURRENCY, SOURCE_SYSTEM, UPDATED_AT, REASONS)
SELECT ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, ORDER_DATE, AMOUNT,
       CURRENCY, SOURCE_SYSTEM, UPDATED_AT, REASONS
FROM SILVER.ORDERS_CHECKED
WHERE ARRAY_SIZE(REASONS) > 0;

-- 4. Rebuild deduplicated orders, keeping latest update per order.
TRUNCATE TABLE SILVER.ORDERS_DEDUP;

INSERT INTO SILVER.ORDERS_DEDUP
    (ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, ORDER_DATE, AMOUNT,
     CURRENCY, AMOUNT_INR, SOURCE_SYSTEM, UPDATED_AT)
SELECT
    ORDER_ID, CUSTOMER_ID, CUSTOMER_NAME, ORDER_DATE, AMOUNT,
    CURRENCY,
    CASE
        WHEN CURRENCY = 'INR' THEN AMOUNT
        WHEN CURRENCY = 'USD' THEN AMOUNT * 83
        ELSE NULL
    END AS AMOUNT_INR,
    SOURCE_SYSTEM, UPDATED_AT
FROM SILVER.ORDERS_CLEAN
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ORDER_ID
    ORDER BY UPDATED_AT DESC
) = 1;

-- 5. Verify baseline. Expected: 8 bronze, 6 clean, 2 quarantine, 4 dedup.
SELECT COUNT(*) AS BRONZE_ROWS FROM BRONZE.ORDERS_RAW;
SELECT COUNT(*) AS CHECKED_ROWS FROM SILVER.ORDERS_CHECKED;
SELECT COUNT(*) AS CLEAN_ROWS FROM SILVER.ORDERS_CLEAN;
SELECT ORDER_ID, SOURCE_SYSTEM, AMOUNT, REASONS
FROM SILVER.ORDERS_QUARANTINE
ORDER BY ORDER_ID;
SELECT COUNT(*) AS DEDUP_ROWS, SUM(AMOUNT_INR) AS REVENUE_INR
FROM SILVER.ORDERS_DEDUP;
SELECT ORDER_ID, SOURCE_SYSTEM, AMOUNT, AMOUNT_INR, UPDATED_AT
FROM SILVER.ORDERS_DEDUP
ORDER BY ORDER_ID;
