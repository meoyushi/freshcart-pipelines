-- FreshCart assignment: Steps 6–10
-- Run this entire script in a Snowflake SQL worksheet using Run All.
-- It creates the raw, checked, clean, quarantine, deduplicated, and gold tables.
-- All statements use IF NOT EXISTS so rerunning the setup is safe.

USE DATABASE FRESHCART_DB;

-- STEP 6: Bronze raw landing table.
-- VARIANT preserves the original website/mobile payload field names.
CREATE TABLE IF NOT EXISTS BRONZE.ORDERS_RAW (
    RAW_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    SOURCE_SYSTEM VARCHAR(20),
    RAW_PAYLOAD VARIANT,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- STEP 7: Silver standardised/checked and clean tables.
CREATE TABLE IF NOT EXISTS SILVER.ORDERS_CHECKED (
    ORDER_ID VARCHAR(50),
    CUSTOMER_ID VARCHAR(50),
    CUSTOMER_NAME VARCHAR(100),
    ORDER_DATE DATE,
    AMOUNT NUMBER(12,2),
    CURRENCY VARCHAR(10),
    SOURCE_SYSTEM VARCHAR(20),
    UPDATED_AT TIMESTAMP_NTZ,
    REASONS ARRAY
);

-- The assignment's B1 baseline explicitly checks silver.orders_clean.
CREATE TABLE IF NOT EXISTS SILVER.ORDERS_CLEAN (
    ORDER_ID VARCHAR(50),
    CUSTOMER_ID VARCHAR(50),
    CUSTOMER_NAME VARCHAR(100),
    ORDER_DATE DATE,
    AMOUNT NUMBER(12,2),
    CURRENCY VARCHAR(10),
    SOURCE_SYSTEM VARCHAR(20),
    UPDATED_AT TIMESTAMP_NTZ
);

-- STEP 8: Silver quarantine table for rejected records and their reasons.
CREATE TABLE IF NOT EXISTS SILVER.ORDERS_QUARANTINE (
    ORDER_ID VARCHAR(50),
    CUSTOMER_ID VARCHAR(50),
    CUSTOMER_NAME VARCHAR(100),
    ORDER_DATE DATE,
    AMOUNT NUMBER(12,2),
    CURRENCY VARCHAR(10),
    SOURCE_SYSTEM VARCHAR(20),
    UPDATED_AT TIMESTAMP_NTZ,
    REASONS ARRAY,
    QUARANTINED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- STEP 9: Silver deduplicated table.
CREATE TABLE IF NOT EXISTS SILVER.ORDERS_DEDUP (
    ORDER_ID VARCHAR(50),
    CUSTOMER_ID VARCHAR(50),
    CUSTOMER_NAME VARCHAR(100),
    ORDER_DATE DATE,
    AMOUNT NUMBER(12,2),
    CURRENCY VARCHAR(10),
    AMOUNT_INR NUMBER(12,2),
    SOURCE_SYSTEM VARCHAR(20),
    UPDATED_AT TIMESTAMP_NTZ
);

-- STEP 10: Gold fact table for published order metrics.
CREATE TABLE IF NOT EXISTS GOLD.FCT_ORDERS (
    ORDER_ID VARCHAR(50),
    CUSTOMER_ID VARCHAR(50),
    CUSTOMER_NAME VARCHAR(100),
    ORDER_DATE DATE,
    AMOUNT NUMBER(12,2),
    CURRENCY VARCHAR(10),
    AMOUNT_INR NUMBER(12,2),
    LOYALTY_POINTS NUMBER(12,2),
    PUBLISHED_AT TIMESTAMP_NTZ,
    ROW_HASH VARCHAR(64)
);

